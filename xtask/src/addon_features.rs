//! `cargo xtask addon-features`: generates the family lines of `crates/addon/addon/Cargo.toml`
//! from the family crates under `crates/addon/families/`.
//!
//! Two blocks of the manifest are generated, each between a begin and an end marker comment:
//! in `[features]`, the `molang` and `nbt` lines (their entries that are not family forwards are
//! kept as the file has them), one `name = ["dep:bedrock_addon_family_name"]` line for every
//! family with no hand line, and `full`; in `[dependencies]`, one optional path dependency per
//! family crate. A feature line that pulls in more than its family's crate is written by hand
//! above the markers and is left alone, as is every other line of the file. Every manifest is
//! read with the `toml` crate, so a family crate is found by what its `Cargo.toml` says, not by
//! how it is formatted.
//!
//! Both blocks are rendered from one reading of the tree and written in one rename, so the
//! dependency line and the feature line of a family arrive together: cargo loads every member's
//! manifest, and a feature naming a missing `dep:` would stop every cargo command, this one too.
//! That is also the order an author keeps: a new family crate first, then this command, then
//! (if needed) its feature line moved into the hand block and the command again; to remove a
//! family, delete its generated lines by hand, then the crate, then run the command.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::Path;
use std::{fs, io};

/// The composing crate's manifest, relative to the workspace root.
pub const MANIFEST: &str = "crates/addon/addon/Cargo.toml";
/// The directory of the family crates, relative to the workspace root.
pub const FAMILIES: &str = "crates/addon/families";
/// The prefix of every family crate's package name; the rest is the family's feature name.
pub const CRATE_PREFIX: &str = "bedrock_addon_family_";
/// The features of the composing crate that forward to every family crate that has them.
pub const FORWARDED: [&str; 2] = ["molang", "nbt"];

/// The marker lines around the generated feature lines.
const FEATURES_BEGIN: &str =
    "# begin generated by `cargo xtask addon-features`: the family features";
const FEATURES_END: &str = "# end generated: the family features";
/// The marker lines around the generated dependency lines.
const DEPENDENCIES_BEGIN: &str =
    "# begin generated by `cargo xtask addon-features`: the family crates";
const DEPENDENCIES_END: &str = "# end generated: the family crates";

/// Rewrites the generated blocks of the manifest, when they differ from what the tree says.
pub fn run() -> io::Result<()> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .ok_or_else(|| io::Error::other("xtask has no parent directory"))?;
    let path = root.join(MANIFEST);
    let generated = generate(root)?;
    if fs::read_to_string(&path)? == generated {
        return Ok(());
    }
    // One rename, so no reader ever sees a dependency line without its feature line.
    let staged = path.with_extension("toml.addon-features");
    fs::write(&staged, generated)?;
    fs::rename(staged, path)
}

/// The manifest of the composing crate with its generated blocks rendered from the family
/// crates under `root`.
///
/// Fails when a manifest does not parse, a marker is missing, a family crate's name lacks the
/// prefix, or a hand feature line named after a family does not enable that family's crate.
pub fn generate(root: &Path) -> io::Result<String> {
    let families = read_families(&root.join(FAMILIES))?;
    let text = fs::read_to_string(root.join(MANIFEST))?;
    let hand = hand_features(&text)?;
    let current = features_of(&parse(&text, MANIFEST)?);
    let features = render_features(&families, &hand, &current)?;
    let dependencies = render_dependencies(&families);
    let text = splice(&text, FEATURES_BEGIN, FEATURES_END, &features)?;
    splice(&text, DEPENDENCIES_BEGIN, DEPENDENCIES_END, &dependencies)
}

/// One family crate: its feature name, its directory and the features of its own manifest.
#[derive(Debug)]
pub struct Family {
    /// The feature and module name, the package name without [`CRATE_PREFIX`].
    pub name: String,
    /// The directory under [`FAMILIES`].
    pub dir: String,
    /// The keys of the crate's `[features]`.
    pub features: BTreeSet<String>,
}

impl Family {
    /// The package name of the family crate.
    pub fn crate_name(&self) -> String {
        format!("{CRATE_PREFIX}{}", self.name)
    }
}

/// Every family crate under `dir`, sorted by name.
pub fn read_families(dir: &Path) -> io::Result<Vec<Family>> {
    let mut families = Vec::new();
    for entry in fs::read_dir(dir)? {
        let entry = entry?;
        let manifest = entry.path().join("Cargo.toml");
        if !manifest.is_file() {
            continue;
        }
        let dir_name = entry.file_name().to_string_lossy().into_owned();
        let label = format!("{FAMILIES}/{dir_name}/Cargo.toml");
        let table = parse(&fs::read_to_string(&manifest)?, &label)?;
        let package = table
            .get("package")
            .and_then(|package| package.get("name"))
            .and_then(toml::Value::as_str)
            .ok_or_else(|| error(format!("{label}: no package name")))?;
        let name = package.strip_prefix(CRATE_PREFIX).ok_or_else(|| {
            error(format!(
                "{label}: {package} does not start with {CRATE_PREFIX}"
            ))
        })?;
        families.push(Family {
            name: name.to_owned(),
            dir: dir_name,
            features: features_of(&table).into_keys().collect(),
        });
    }
    families.sort_by(|a, b| a.name.cmp(&b.name));
    Ok(families)
}

/// The features written by hand: those of the manifest with its generated blocks emptied.
fn hand_features(text: &str) -> io::Result<BTreeMap<String, Vec<String>>> {
    let text = splice(text, FEATURES_BEGIN, FEATURES_END, "")?;
    let text = splice(&text, DEPENDENCIES_BEGIN, DEPENDENCIES_END, "")?;
    Ok(features_of(&parse(&text, MANIFEST)?))
}

/// The generated feature lines: the forwards, the plain family lines, then `full`.
fn render_features(
    families: &[Family],
    hand: &BTreeMap<String, Vec<String>>,
    current: &BTreeMap<String, Vec<String>>,
) -> io::Result<String> {
    let crates: BTreeSet<String> = families.iter().map(Family::crate_name).collect();
    for family in families {
        if let Some(line) = hand.get(&family.name)
            && !line.contains(&format!("dep:{}", family.crate_name()))
        {
            return Err(error(format!(
                "{MANIFEST}: the hand line `{}` does not enable dep:{}",
                family.name,
                family.crate_name()
            )));
        }
    }
    let mut out = String::new();
    for feature in FORWARDED {
        let mut entries: Vec<String> = current
            .get(feature)
            .into_iter()
            .flatten()
            .filter(|entry| !entry.starts_with(CRATE_PREFIX))
            .cloned()
            .collect();
        entries.extend(
            families
                .iter()
                .filter(|family| family.features.contains(feature))
                .map(|family| format!("{}?/{feature}", family.crate_name())),
        );
        array(&mut out, feature, &entries);
    }
    let mut full = BTreeSet::new();
    for family in families {
        if !hand.contains_key(&family.name) {
            let _ = writeln!(out, "{} = [\"dep:{}\"]", family.name, family.crate_name());
        }
        full.insert(family.name.clone());
    }
    // A hand feature over a family crate that is not named after it (`languages`) is a family
    // feature too.
    for (feature, entries) in hand {
        let enables = entries
            .iter()
            .filter_map(|entry| entry.strip_prefix("dep:"));
        let mut family_crates = enables
            .filter(|dep| dep.starts_with(CRATE_PREFIX))
            .peekable();
        if family_crates.peek().is_none() {
            continue;
        }
        for dep in family_crates {
            if !crates.contains(dep) {
                return Err(error(format!(
                    "{MANIFEST}: `{feature}` enables dep:{dep}, which is no crate under {FAMILIES}"
                )));
            }
        }
        full.insert(feature.clone());
    }
    let full: Vec<String> = full.into_iter().collect();
    array(&mut out, "full", &full);
    Ok(out)
}

/// The generated dependency lines, one per family crate.
fn render_dependencies(families: &[Family]) -> String {
    let mut out = String::new();
    for family in families {
        let _ = writeln!(
            out,
            "{} = {{ path = \"../families/{}\", optional = true }}",
            family.crate_name(),
            family.dir
        );
    }
    out
}

/// Appends `key = [ … ]`, one quoted entry per line.
fn array(out: &mut String, key: &str, entries: &[String]) {
    let _ = writeln!(out, "{key} = [");
    for entry in entries {
        let _ = writeln!(out, "    \"{entry}\",");
    }
    let _ = writeln!(out, "]");
}

/// `text` with the lines between the `begin` and `end` marker lines replaced by `body`.
fn splice(text: &str, begin: &str, end: &str, body: &str) -> io::Result<String> {
    let missing = |marker: &str| error(format!("{MANIFEST}: no marker line `{marker}`"));
    let start = text
        .find(&format!("{begin}\n"))
        .ok_or_else(|| missing(begin))?
        + begin.len()
        + 1;
    let stop = start
        + text[start..]
            .find(&format!("{end}\n"))
            .ok_or_else(|| missing(end))?;
    Ok(format!("{}{body}{}", &text[..start], &text[stop..]))
}

/// The `[features]` of a parsed manifest, each with its entries.
fn features_of(table: &toml::Table) -> BTreeMap<String, Vec<String>> {
    let Some(features) = table.get("features").and_then(toml::Value::as_table) else {
        return BTreeMap::new();
    };
    features
        .iter()
        .map(|(name, entries)| {
            let entries = entries
                .as_array()
                .into_iter()
                .flatten()
                .filter_map(toml::Value::as_str)
                .map(str::to_owned)
                .collect();
            (name.clone(), entries)
        })
        .collect()
}

fn parse(text: &str, label: &str) -> io::Result<toml::Table> {
    text.parse::<toml::Table>()
        .map_err(|e| error(format!("{label}: {e}")))
}

fn error(message: impl Into<String>) -> io::Error {
    io::Error::new(io::ErrorKind::InvalidData, message.into())
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    fn workspace_root() -> PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .unwrap()
            .to_path_buf()
    }

    fn committed_manifest() -> String {
        fs::read_to_string(workspace_root().join(MANIFEST)).unwrap()
    }

    fn committed_features() -> BTreeMap<String, Vec<String>> {
        features_of(&parse(&committed_manifest(), MANIFEST).unwrap())
    }

    fn families() -> Vec<Family> {
        read_families(&workspace_root().join(FAMILIES)).unwrap()
    }

    #[test]
    fn the_family_lines_of_the_addon_manifest_are_generated() {
        let generated = generate(&workspace_root()).unwrap();
        assert!(
            generated == committed_manifest(),
            "{MANIFEST} is not what `cargo xtask addon-features` generates; run it"
        );
    }

    #[test]
    fn every_family_crate_has_a_feature() {
        let features = committed_features();
        for family in families() {
            let line = features.get(&family.name);
            let dep = format!("dep:{}", family.crate_name());
            assert!(
                line.is_some_and(|line| line.contains(&dep)),
                "{} has no feature `{}` enabling {dep}",
                family.dir,
                family.name
            );
        }
    }

    #[test]
    fn full_is_every_family_feature() {
        let features = committed_features();
        let full: BTreeSet<&str> = features["full"].iter().map(String::as_str).collect();
        let over_a_family: BTreeSet<&str> = features
            .iter()
            .filter(|(_, entries)| {
                entries
                    .iter()
                    .any(|entry| entry.starts_with(&format!("dep:{CRATE_PREFIX}")))
            })
            .map(|(name, _)| name.as_str())
            .collect();
        assert_eq!(full, over_a_family);
    }

    #[test]
    fn molang_forwards_every_family_with_a_molang_feature() {
        let features = committed_features();
        let forwarded: BTreeSet<String> = features["molang"]
            .iter()
            .filter_map(|entry| entry.strip_suffix("?/molang"))
            .map(str::to_owned)
            .collect();
        let with_molang: BTreeSet<String> = families()
            .iter()
            .filter(|family| family.features.contains("molang"))
            .map(Family::crate_name)
            .collect();
        assert_eq!(forwarded, with_molang);
    }
}
