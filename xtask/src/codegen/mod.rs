/// Shared by every generator's per-version emitter (`codegen::palette::emit`,
/// `codegen::biome::emit`): the generated module name for one version, e.g. `v1_20_10`
/// for `(1, 20, 10)` with an empty `prefix`, or `biome_v1_21_130` for `(1, 21, 130)` with
/// `prefix` `"biome_"`. The prefix is what keeps two generators' per-version files from
/// colliding in the shared `crates/vanilla_data/src/generated/` output directory.
pub fn versioned_module_name(prefix: &str, game_version: (u8, u8, u8)) -> String {
    let (major, minor, patch) = game_version;
    format!("{prefix}v{major}_{minor}_{patch}")
}

/// Shared by every generator's per-version emitter: the `#![doc = ...]` header text a
/// generated per-version file starts with -- built as a plain string (not a `//!` line
/// comment) because a `//!` comment is converted to its `#[doc]` attribute by the
/// compiler's lexer before `quote!` ever sees it, which happens too early for `quote!`'s
/// own `#var` interpolation to reach into its text.
pub fn generated_header(tag: &str, source_path: &str, generator_path: &str) -> String {
    format!(
        " Generated by `cargo xtask generate-palette` from the `{tag}` release of \
          `Mojang/bedrock-samples`, path `{source_path}`. Do not edit by hand -- edit \
          the generator (`{generator_path}`) or the pinned dump \
          (`xtask/dumps/bedrock-samples`) instead, and regenerate."
    )
}
