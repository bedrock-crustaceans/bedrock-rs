#[test]
fn an_item_added_twice_is_rejected() {
    // `v3` adds what `v1` added, where `%` would replace it.
    let definition =
        DEFINITION.replace("% LoginPacket: LoginPacket,", "+ LoginPacket: LoginPacket,");
    let error = definition_error(&definition);
    assert_eq!(pointed_at(&error), "LoginPacket");
    // The error is at the second `+`, not at the first.
    let added = definition.lines().enumerate();
    let second = added
        .filter(|(_, line)| line.contains("+ LoginPacket"))
        .last();
    assert_eq!(
        Some(error.span().start().line),
        second.map(|(index, _)| index + 1)
    );
}

