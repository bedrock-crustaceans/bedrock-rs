#[test]
fn two_versions_of_one_number_stay_in_the_order_of_the_file() {
    let files = rendered(HOTFIX, &tree_of(&[]));
    let hotfix = &files["version/v5hotfix/src/generated.rs"];
    assert_has(hotfix, "pub enum V5Hotfix {");
    assert_has(hotfix, "const PROTOCOL_VERSION: u32 = 5u32;");
    assert_has(hotfix, "type ScorePacket = crate::packets::ScorePacket;");

    // The version after the hotfix names an item of the version before it: the owner is the
    // module the `in` path says, whatever the numbers are.
    assert_has(
        &files["version/v6/src/generated.rs"],
        "type ScorePacket = bedrock_protocol_v5::packets::OldScorePacket;",
    );
    let v6 = manifest(&files, "version/v6/Cargo.toml");
    assert!(dependencies(&v6).contains("bedrock_protocol_v5"));
    assert!(!dependencies(&v6).contains("bedrock_protocol_v5hotfix"));

    let facade = manifest(&files, FACADE_MANIFEST);
    assert_eq!(feature(&facade, "all"), ["v5", "v5hotfix", "v6"]);
}

/// Whether the generator has nothing to say against the tree.
fn accepts(definition: &str, tree: &Tree) -> bool {
    render(definition, tree).is_ok_and(|rendering| rendering.left_behind.is_none())
}

/// The error of a tree the generator rejects.
fn tree_error(definition: &str, tree: &Tree) -> Error {
    match render(definition, tree) {
        Err(error) => error,
        Ok(rendering) => rendering.left_behind.expect("the tree was accepted"),
    }
}

#[test]
fn a_source_that_names_a_later_version_crate_is_rejected() {
    let text = "use bedrock_protocol_v3::packets::LoginPacket;";
    let error = tree_error(DEFINITION, &tree_of(&[("v2", "packets/text.rs", text)]));
    assert!(
        matches!(
            &error,
            Error::SourceNamesLaterVersion { module, file, name }
                if module == "v2" && file == "packets/text.rs" && name == "bedrock_protocol_v3"
        ),
        "{error:?}"
    );

    // The generated code is not a source, and the same name is fine in a later crate.
    assert!(accepts(
        DEFINITION,
        &tree_of(&[("v2", "generated.rs", text)])
    ));
    let in_v3 = text.replace("v3", "v2");
    assert!(accepts(
        DEFINITION,
        &tree_of(&[("v3", "packets/login.rs", in_v3.as_str())])
    ));
}

#[test]
