use super::*;

/// Three versions. `v2` carries `LoginPacket` and `Difficulty` forward from `v1`; `v3` replaces
/// both, so all it carries forward is of `v2`.
const DEFINITION: &str = r#"versions![
    (1, "r/1", "1.0.0"): {
        raknet_version: 10,
        packets: [
            + LoginPacket: LoginPacket,
            + TextPacket: TextPacket^,
        ] in v1::packets,
        enums: [
            + Difficulty: Difficulty,
        ] in v1::enums,
    },
    (2, "r/2", "2.0.0"): {
        packets: [
            % TextPacket: TextPacket^,
        ] in v2::packets,
        types: [
            + Vec3: math::Vec3,
        ] in v2::types,
    },
    (3, "r/3", "3.0.0"): {
        packets: [
            % LoginPacket: LoginPacket,
        ] in v3::packets,
        enums: [
            % Difficulty: Difficulty,
        ] in v3::enums,
    },
];"#;

/// A version, a hotfix of it under the same protocol number, and a version after both that goes
/// back to an item of the first.
const HOTFIX: &str = r#"versions![
    (5, "r/5", "5.0.0"): {
        raknet_version: 11,
        packets: [
            + ScorePacket: ScorePacket,
        ] in v5::packets,
    },
    (5, "r/5_hotfix", "5.0.1"): {
        packets: [
            % ScorePacket: ScorePacket,
        ] in v5hotfix::packets,
    } as V5Hotfix,
    (6, "r/6", "6.0.0"): {
        packets: [
            % ScorePacket: OldScorePacket,
        ] in v5::packets,
    },
];"#;

/// A facade manifest: hand-written lines around the two generated blocks, both stale.
const FACADE: &str = r#"[package]
name = "bedrock_protocol"

[dependencies]
bedrock_protocol_core = { path = "../core" }
# begin generated by `cargo xtask`: the version crates
bedrock_protocol_v0 = { path = "../version/v0", default-features = false }
# end generated: the version crates

[features]
packet-trace = ["bedrock_protocol_core/packet-trace"]
# begin generated by `cargo xtask`: the version features
default = []
v0 = ["bedrock_protocol_v0/version"]
# end generated: the version features

[[test]]
name = "trace"
"#;

const V1_MANIFEST: &str = "version/v1/Cargo.toml";
const V2_MANIFEST: &str = "version/v2/Cargo.toml";
const V3_MANIFEST: &str = "version/v3/Cargo.toml";
const V1_GENERATED: &str = "version/v1/src/generated.rs";
const V2_GENERATED: &str = "version/v2/src/generated.rs";
const V3_GENERATED: &str = "version/v3/src/generated.rs";

/// A tree of `(version module, path below src/, text)` files and the stale facade manifest.
fn tree_of(files: &[(&str, &str, &str)]) -> Tree {
    let mut tree = Tree {
        facade_manifest: FACADE.to_owned(),
        ..Tree::default()
    };
    for (module, path, text) in files {
        let sources = tree.sources.entry((*module).to_owned()).or_default();
        sources.insert((*path).to_owned(), (*text).to_owned());
    }
    tree
}

/// What the generator renders, by path.
fn rendered(definition: &str, tree: &Tree) -> BTreeMap<String, String> {
    let outputs = render(definition, tree).unwrap().outputs;
    let files = outputs.into_iter();
    files.map(|file| (file.path, file.contents)).collect()
}

/// The files rendered from [`DEFINITION`] over a tree in which `v3` has the one source `text`.
fn rendered_with_v3_source(text: &str) -> BTreeMap<String, String> {
    rendered(DEFINITION, &tree_of(&[("v3", "packets/login.rs", text)]))
}

fn manifest(files: &BTreeMap<String, String>, path: &str) -> toml::Table {
    files[path].parse().unwrap()
}

/// The names of a manifest's dependencies.
fn dependencies(manifest: &toml::Table) -> BTreeSet<&str> {
    let dependencies = manifest["dependencies"].as_table().unwrap();
    dependencies.keys().map(String::as_str).collect()
}

fn is_optional(manifest: &toml::Table, dependency: &str) -> bool {
    let dependency = &manifest["dependencies"][dependency];
    dependency.get("optional").and_then(toml::Value::as_bool) == Some(true)
}

/// The entries of one feature of a manifest.
fn feature<'a>(manifest: &'a toml::Table, name: &str) -> Vec<&'a str> {
    let entries = manifest["features"][name].as_array().unwrap();
    entries.iter().map(|e| e.as_str().unwrap()).collect()
}

/// The error of a definition the generator rejects.
fn definition_error(definition: &str) -> syn::Error {
    match render(definition, &tree_of(&[])) {
        Err(Error::Definition(error)) => error,
        Err(error) => panic!("not a definition error: {error}"),
        Ok(_) => panic!("the definition was accepted"),
    }
}

/// The text of the definition the error points at.
fn pointed_at(error: &syn::Error) -> String {
    error.span().source_text().unwrap()
}

#[track_caller]
fn assert_has(text: &str, needle: &str) {
    assert!(text.contains(needle), "no `{needle}` in:\n{text}");
}

