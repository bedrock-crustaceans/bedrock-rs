//! The manifests the generator writes: the whole `Cargo.toml` of every version crate, and the
//! two blocks of the facade's between its marker lines.
//!
//! What a version crate depends on is read off two things: the items the version carries
//! forward (their owner crates), and the names its hand-written sources use. "The sources" are
//! every `.rs` file under the crate's `src/` but `generated.rs`; a source "names" a crate when
//! the crate's name stands in it as a whole word outside a line comment. Prose and doc examples
//! name crates without using them, so a line is read up to its first `//`; a block comment and
//! a string literal are read as code (and a `//` inside a string ends its line here too). The
//! rules, in the order of the `[dependencies]` they write:
//!
//! 1. `bedrock_protocol_core`, always: the generated code is written in its terms.
//! 2. `bedrock_protocol_version`, always: the generated code implements its traits.
//! 3. `bedrock_macros`, when the sources name it.
//! 4. Every other version crate that owns an item of this version or that the sources name, in
//!    the order of the versions, each with `default-features = false`: a dependent never makes
//!    an older version compile its packet enum.
//! 5. The crates of [`EXTERNAL`] the sources need: one whose name starts a path (`uuid::`) in
//!    them, `nbtx` and `tracing` when (3) holds (the derive expands to `::tracing::trace!` and,
//!    for an `#[nbt]` field, to `::nbtx::…`), and `strum` with `strum_macros` (its derives
//!    expand to `::strum::…`).
//!
//! A dependency of (1), (2) or (4) that the sources do not need is there for `generated.rs`
//! alone. That file compiles only under the `version` feature, which no dependent turns on, so
//! such a dependency is `optional = true` and `version` enables it: otherwise it would be built
//! for nothing and cargo would report it as unused. The sources need (2) and (4) when they name
//! the crate, and core when they name it or name `bedrock_macros`, whose derive expands to
//! `::bedrock_protocol_core::…` paths. `packet-dyn` and `packet-meta` forward to core and to
//! every dependency of (4), to an optional one in the weak form (`name?/feature`).
//!
//! A version crate can only use the crates of older versions, since every later one depends on
//! it: a source that names a later version's crate, or its own crate (which inside it is
//! `crate`), is an error.

use crate::codegen::protocol::diff::crate_name;
use crate::codegen::protocol::{DEFINITION, Error, ROOT, Sources, Version};
use crate::markers::{self, MissingMarker};
use std::cmp::Ordering;
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

/// The crate of the `ProtoVersion*` traits.
const TRAITS: &str = "bedrock_protocol_version";
/// The crate of the derives.
const MACROS: &str = "bedrock_macros";
/// The workspace dependencies a version crate may need, in the order they are written.
const EXTERNAL: [&str; 6] = [
    "byteorder",
    "nbtx",
    "strum",
    "strum_macros",
    "tracing",
    "uuid",
];
/// The second line of a version crate's manifest: where to go when a source uses a crate the
/// manifest does not list. It names this file by its path from the workspace root.
const WHERE_THE_RULES_ARE: &str = "# Dependencies follow the names the sources use; the external \
     crates the generator knows are EXTERNAL in xtask/src/codegen/protocol/manifest.rs.";
/// The features every version crate and the facade forward to the crates below them.
const FORWARDED: [&str; 2] = ["packet-dyn", "packet-meta"];

/// The marker lines around the facade's dependencies on the version crates.
const DEPENDENCIES_BEGIN: &str = "# begin generated by `cargo xtask`: the version crates";
const DEPENDENCIES_END: &str = "# end generated: the version crates";
/// The marker lines around the facade's version features.
const FEATURES_BEGIN: &str = "# begin generated by `cargo xtask`: the version features";
const FEATURES_END: &str = "# end generated: the version features";

/// The crate every version crate's generated code is written against.
const CORE: &str = "bedrock_protocol_core";

/// The words of a crate's hand-written sources: `[A-Za-z0-9_]+` runs.
#[derive(Default)]
struct Names<'a> {
    /// Every word, with the path of the first source that has it.
    words: BTreeMap<&'a str, &'a str>,
    /// The words directly followed by `::`.
    path_heads: BTreeSet<&'a str>,
}

impl<'a> Names<'a> {
    /// The words of every source but `generated.rs`.
    fn of(sources: &'a Sources) -> Self {
        let mut names = Self::default();
        for (path, text) in sources {
            if path != "generated.rs" {
                names.read(path, text);
            }
        }
        names
    }

    /// Adds the words of the source `text` at `path`, each line up to its line comment.
    fn read(&mut self, path: &'a str, text: &'a str) {
        let is_word = |c: char| c.is_alphanumeric() || c == '_';
        for line in text.lines() {
            let mut rest = line.split_once("//").map_or(line, |(code, _)| code);
            while let Some(start) = rest.find(is_word) {
                let from_word = &rest[start..];
                let end = from_word.find(|c| !is_word(c));
                let (word, after) = from_word.split_at(end.unwrap_or(from_word.len()));
                self.words.entry(word).or_insert(path);
                if after.starts_with("::") {
                    self.path_heads.insert(word);
                }
                rest = after;
            }
        }
    }

    fn has(&self, word: &str) -> bool {
        self.words.contains_key(word)
    }
}

/// A dependency on another crate of the protocol that the generated code needs.
struct Dependency {
    name: String,
    /// Whether the sources do not need it: `generated.rs` is then its one user.
    optional: bool,
}

/// What one version crate depends on.
struct Dependencies {
    core: Dependency,
    traits: Dependency,
    macros: bool,
    versions: Vec<(String, Dependency)>,
    external: Vec<&'static str>,
}

impl Dependencies {
    /// What the crate of `version` depends on, `versions` being every version in order.
    fn of(version: &Version, versions: &[Version], sources: &Sources) -> Result<Self, Error> {
        let names = Names::of(sources);
        let macros = names.has(MACROS);
        let by_name = |name: String| Dependency {
            optional: !names.has(&name),
            name,
        };

        // A version crate is a dependency when the sources name it or it owns an item. Only an
        // older one may be named: this crate is `crate` to itself, and a later one depends on it.
        let owners: BTreeSet<_> = version.items().map(|item| &item.owner).collect();
        let is_own = |other: &Version| other.module == version.module;
        let own = versions.iter().position(is_own).unwrap_or(versions.len());
        let mut version_crates = Vec::new();
        for (index, other) in versions.iter().enumerate() {
            let dependency = by_name(other.crate_name());
            if let Some(file) = names.words.get(dependency.name.as_str()) {
                let (module, file) = (version.module.to_string(), (*file).to_owned());
                match index.cmp(&own) {
                    Ordering::Less => {}
                    Ordering::Equal => return Err(Error::SourceNamesOwnCrate { module, file }),
                    Ordering::Greater => {
                        let name = dependency.name;
                        return Err(Error::SourceNamesLaterVersion { module, file, name });
                    }
                }
            }
            if index != own && (!dependency.optional || owners.contains(&other.module)) {
                version_crates.push((other.module.to_string(), dependency));
            }
        }

        let mut external: BTreeSet<&str> = EXTERNAL
            .into_iter()
            .filter(|name| names.path_heads.contains(name))
            .collect();
        if macros {
            external.extend(["nbtx", "tracing"]);
        }
        if external.contains("strum_macros") {
            external.insert("strum");
        }

        Ok(Self {
            // The derive expands to paths into core, so naming the derive is needing core.
            core: Dependency {
                name: CORE.to_owned(),
                optional: !macros && !names.has(CORE),
            },
            traits: by_name(TRAITS.to_owned()),
            macros,
            versions: version_crates,
            external: external.into_iter().collect(),
        })
    }

    /// The crates of the protocol that are optional, in the order they are written.
    fn optional(&self) -> impl Iterator<Item = &Dependency> {
        let versions = self.versions.iter().map(|(_, dependency)| dependency);
        [&self.core, &self.traits]
            .into_iter()
            .chain(versions)
            .filter(|dependency| dependency.optional)
    }

    /// The crates `packet-dyn` and `packet-meta` forward to: core and the version crates.
    fn forwarded(&self) -> impl Iterator<Item = &Dependency> {
        let versions = self.versions.iter().map(|(_, dependency)| dependency);
        std::iter::once(&self.core).chain(versions)
    }
}

/// The whole `Cargo.toml` of one version crate. `versions` is every version, in order; `sources`
/// the crate's own files.
///
/// # Errors
///
/// Returns an error if a source names the crate itself or the crate of a later version.
pub fn version(
    version: &Version,
    versions: &[Version],
    sources: &Sources,
) -> Result<String, Error> {
    let dependencies = Dependencies::of(version, versions, sources)?;
    let name = version.crate_name();
    let optional = |dependency: &Dependency| {
        if dependency.optional {
            ", optional = true"
        } else {
            ""
        }
    };

    let mut out = format!(
        "# Generated by `cargo xtask` from {ROOT}/{DEFINITION}. Do not edit.\n\
         {WHERE_THE_RULES_ARE}\n\
         [package]\n\
         name = \"{name}\"\n\
         version.workspace = true\n\
         edition.workspace = true\n\
         \n\
         [lints]\n\
         workspace = true\n\
         \n\
         [dependencies]\n"
    );
    let core = optional(&dependencies.core);
    let _ = writeln!(out, "{CORE} = {{ path = \"../../core\"{core} }}");
    let traits = optional(&dependencies.traits);
    let _ = writeln!(out, "{TRAITS} = {{ path = \"../traits\"{traits} }}");
    if dependencies.macros {
        let _ = writeln!(out, "{MACROS} = {{ path = \"../../macros\" }}");
    }
    for (module, dependency) in &dependencies.versions {
        let Dependency { name, .. } = dependency;
        let optional = optional(dependency);
        let _ = writeln!(
            out,
            "{name} = {{ path = \"../{module}\", default-features = false{optional} }}"
        );
    }
    for name in &dependencies.external {
        let _ = writeln!(out, "{name}.workspace = true");
    }

    let enum_ident = &version.enum_ident;
    let _ = write!(
        out,
        "\n\
         [features]\n\
         default = [\"version\"]\n\
         # The `{enum_ident}` packet enum and its `ProtoVersion` impls (`src/generated.rs`).\n"
    );
    let enabled: Vec<String> = dependencies
        .optional()
        .map(|dependency| format!("dep:{}", dependency.name))
        .collect();
    if enabled.is_empty() {
        out.push_str("version = []\n");
    } else {
        array(&mut out, "version", &enabled);
    }
    for feature in FORWARDED {
        let entries: Vec<String> = dependencies
            .forwarded()
            .map(|dependency| {
                let weak = if dependency.optional { "?" } else { "" };
                format!("{}{weak}/{feature}", dependency.name)
            })
            .collect();
        array(&mut out, feature, &entries);
    }
    Ok(out)
}

/// The facade's manifest with its two generated blocks rendered for `versions`.
///
/// # Errors
///
/// Returns [`Error::MissingMarker`] if `manifest` lacks one of the four marker lines.
pub fn facade(versions: &[Version], manifest: &str) -> Result<String, Error> {
    let text = splice(
        manifest,
        DEPENDENCIES_BEGIN,
        DEPENDENCIES_END,
        &facade_dependencies(versions),
    )?;
    splice(
        &text,
        FEATURES_BEGIN,
        FEATURES_END,
        &facade_features(versions),
    )
}

/// One line per version crate, each without its default feature: the packet enum of a version
/// compiles only when the facade's feature of that version is on.
fn facade_dependencies(versions: &[Version]) -> String {
    let mut out = String::new();
    for version in versions {
        let (name, module) = (version.crate_name(), &version.module);
        let _ = writeln!(
            out,
            "{name} = {{ path = \"../version/{module}\", default-features = false }}"
        );
    }
    out
}

/// `default` (the newest version), one feature per version, `all`, and the forwarded features.
fn facade_features(versions: &[Version]) -> String {
    let modules: Vec<String> = versions.iter().map(|v| v.module.to_string()).collect();
    let mut out = String::new();
    match modules.last() {
        Some(newest) => {
            let _ = writeln!(out, "default = [\"{newest}\"]");
        }
        None => out.push_str("default = []\n"),
    }
    for version in versions {
        let (name, module) = (version.crate_name(), &version.module);
        let _ = writeln!(out, "{module} = [\"{name}/version\"]");
    }
    array(&mut out, "all", &modules);
    for feature in FORWARDED {
        let mut entries = vec![format!("bedrock_protocol_core/{feature}")];
        entries.extend(
            modules
                .iter()
                .map(|m| format!("{}/{feature}", crate_name(m))),
        );
        array(&mut out, feature, &entries);
    }
    out
}

/// Appends `key = [ … ]`, one quoted entry per line.
fn array(out: &mut String, key: &str, entries: &[String]) {
    let _ = writeln!(out, "{key} = [");
    for entry in entries {
        let _ = writeln!(out, "    \"{entry}\",");
    }
    let _ = writeln!(out, "]");
}

/// `text` with the lines between the `begin` and `end` marker lines replaced by `body`.
fn splice(text: &str, begin: &'static str, end: &'static str, body: &str) -> Result<String, Error> {
    markers::splice(text, begin, end, body)
        .map_err(|MissingMarker(marker)| Error::MissingMarker(marker))
}

