//! `cargo xtask entity-schemas` (second part): renders
//! `crates/addon/families/entity/src/game_schema/numeric_table.rs` from the dump of the numeric
//! checks the game's goal readers run on their members,
//! `xtask/src/script_meta/game/entity_goal_numeric_checks.tsv` (one row per numeric check of a
//! goal member: its comparison, bound, default and message text).
//!
//! Plain `std`; the test `the_committed_numeric_table_is_the_render_of_the_dump` checks the
//! committed table. The table is one `#[rustfmt::skip]` item.

use std::fmt::Write as _;
use std::io;

/// The dump, relative to the workspace root.
pub const INPUT: &str = "xtask/src/script_meta/game/entity_goal_numeric_checks.tsv";
/// The generated table, relative to the workspace root.
pub const OUTPUT: &str = "crates/addon/families/entity/src/game_schema/numeric_table.rs";

/// One check: a row of the dump the game runs.
#[derive(Debug, PartialEq)]
pub struct Check {
    /// The goal's key.
    pub goal: String,
    /// The member checked (for a dependency, the upper member).
    pub member: String,
    /// The crate's `Kind` variant.
    pub kind: &'static str,
    /// The bound (the upper end of a range; the lower member of a dependency is in `dependency`).
    pub bound: String,
    /// The default the member takes on a failure.
    pub default: String,
    /// The lower member of a dependency, else empty.
    pub dependency: String,
    /// The text, the value's place as `{}`.
    pub template: String,
}

fn error(message: impl Into<String>) -> io::Error {
    io::Error::new(io::ErrorKind::InvalidData, message.into())
}

/// The checks of the dump the game runs, in the dump's order: a row whose node is shadowed by
/// an earlier one of the same name (its `shadowed` column says so) never runs and is left out.
pub fn parse(dump: &str) -> io::Result<Vec<Check>> {
    let mut out = Vec::new();
    for (number, line) in dump.lines().enumerate().skip(1) {
        if line.trim().is_empty() {
            continue;
        }
        let cells: Vec<&str> = line.split('\t').collect();
        if cells.len() < 9 {
            return Err(error(format!("line {}: {} cells", number + 1, cells.len())));
        }
        if cells[8] == "shadowed" {
            continue;
        }
        let (spec, cmp) = (cells[2], cells[3]);
        let float = spec == "float";
        let kind = match (cmp, float) {
            ("less_equal", false) => "IntAtLeast",
            ("less", false) => "IntAbove",
            ("less_equal", true) => "FloatAtLeast",
            ("less", true) => "FloatAbove",
            ("UnsignedRange", true) => "FloatUpTo",
            ("less(dependency)", true) => "Dependency",
            _ => return Err(error(format!("line {}: variant {spec} {cmp}", number + 1))),
        };
        let template = if kind == "Dependency" {
            // The text the post-parse check prints: both of its names are the empty bound text,
            // so the template carries the member name and empty quotes.
            format!(
                "\"{}\" was less than \"\", defaulting both to \"\" value of {{}}",
                cells[1]
            )
        } else {
            let spec = if float { "%.4f" } else { "%d" };
            if cells[7].matches(spec).count() != 1 {
                return Err(error(format!("line {}: template {}", number + 1, cells[7])));
            }
            cells[7].replace(spec, "{}")
        };
        for number_cell in [cells[4], cells[5]] {
            number_cell
                .parse::<f64>()
                .map_err(|_| error(format!("line {}: number {number_cell}", number + 1)))?;
        }
        out.push(Check {
            goal: cells[0].to_owned(),
            member: cells[1].to_owned(),
            kind,
            bound: cells[4].to_owned(),
            default: cells[5].to_owned(),
            dependency: cells[6].to_owned(),
            template,
        });
    }
    Ok(out)
}

/// A number as a Rust `f64` literal.
fn float(text: &str) -> String {
    if text.contains('.') || text.contains('e') {
        text.to_owned()
    } else {
        format!("{text}.0")
    }
}

/// The table: the checks sorted bytewise by goal, in the dump's order within a goal.
pub fn generate(dump: &str) -> io::Result<String> {
    let mut checks = parse(dump)?;
    checks.sort_by(|a, b| a.goal.as_bytes().cmp(b.goal.as_bytes()));
    let mut out = String::from(
        "// Generated by `cargo xtask entity-schemas` from the game's schema description\n\
         // `xtask/src/script_meta/game/entity_goal_numeric_checks.tsv`. Do not edit: an xtask test checks it.\n\
         \n\
         use super::numeric::{Check, Kind};\n\
         \n\
         /// The numeric checks of the legacy goal readers, sorted bytewise by goal.\n\
         #[rustfmt::skip]\n\
         #[allow(clippy::unreadable_literal, reason = \"the dump's numbers as written\")]\n",
    );
    let _ = writeln!(
        out,
        "pub(super) static CHECKS: [Check; {}] = [",
        checks.len()
    );
    for check in &checks {
        let _ = writeln!(
            out,
            "    Check {{ goal: {:?}, member: {:?}, kind: Kind::{}, bound: {}, default: {}, dependency: {:?}, template: {:?} }},",
            check.goal,
            check.member,
            check.kind,
            float(&check.bound),
            float(&check.default),
            check.dependency,
            check.template
        );
    }
    out.push_str("];\n");
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The crate's table is the render of the dump, byte for byte.
    #[test]
    fn the_committed_numeric_table_is_the_render_of_the_dump() {
        let generated = generate(include_str!(
            "script_meta/game/entity_goal_numeric_checks.tsv"
        ))
        .unwrap();
        assert!(
            generated
                == include_str!(
                    "../../crates/addon/families/entity/src/game_schema/numeric_table.rs"
                ),
            "crates/addon/families/entity/src/game_schema/numeric_table.rs is stale: run `cargo xtask entity-schemas`"
        );
    }

    #[test]
    fn the_committed_numeric_dump_parses_without_its_shadowed_rows() {
        let checks = parse(include_str!(
            "script_meta/game/entity_goal_numeric_checks.tsv"
        ))
        .unwrap();
        // 339 rows, 7 of them shadowed by the base builder's node of the same name.
        assert_eq!(checks.len(), 332);
        assert_eq!(checks.iter().filter(|c| c.kind == "Dependency").count(), 4);
        let work = checks
            .iter()
            .find(|c| c.goal == "minecraft:behavior.work" && c.member == "sound_delay_min")
            .unwrap();
        assert_eq!(
            work.template,
            "\"sound_delay_min\" on minecraft:behavior.work cannot be less than 0, value was {}, defaulting to DefinitionType::DEFAULT_SOUND_DELAY_MIN"
        );
    }
}
