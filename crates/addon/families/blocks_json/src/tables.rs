// The legacy-name and default-shape tables of the client. Every value comes from how the client
// registers its blocks and none is taken from a vanilla data file. What vanilla's resource
// packs can check is checked by the tests over the game's packs, and each table and entry says
// below which it is: "matches the game's packs", "unchecked" (nothing in the game's files states
// it), or, for the 10 positions of `skull` and `purpur_block` whose variants the data draws
// alike, "uncontradicted" by the game's files. `LEGACY_ALIASES` holds each legacy name with its
// gate version and split blocks; `DEFAULT_SHAPES` holds the shape of each block registered with
// one.

