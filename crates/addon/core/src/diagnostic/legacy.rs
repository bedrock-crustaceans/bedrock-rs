/// The legacy variant named `name`.
pub(super) fn legacy(name: &str) -> Option<&'static Legacy> {
    LEGACY.iter().find(|legacy| legacy.name == name)
}

/// Whether `name` is the name of a legacy variant.
pub(super) const fn is_legacy_name(name: &str) -> bool {
    let mut i = 0;
    while i < LEGACY.len() {
        if super::def::str_eq(LEGACY[i].name, name) {
            return true;
        }
        i += 1;
    }
    false
}

/// The names of the legacy variants, in the enum's declaration order: what a definition
/// [`was`](super::CodeDef::was) is checked against.
// hidden: the frozen names of the deleted legacy enum, retired with the pin rename
#[doc(hidden)]
pub fn legacy_names() -> impl ExactSizeIterator<Item = &'static str> {
    LEGACY.iter().map(|legacy| legacy.name)
}
